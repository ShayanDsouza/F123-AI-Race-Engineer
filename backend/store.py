"""Lap storage: one JSON file per recorded lap + an in-memory index.

Laps live in data/laps/<id>.json. The id encodes track/session/time so files
are self-describing even outside the app.

A lap file carries the whole telemetry trace (tens of kB for an opponent,
hundreds for the player), while a lap *listing* only needs the header. The
index caches one summary per file keyed on mtime+size, so listing a few
hundred laps every few seconds while the game is running costs a directory
scan, not a re-parse of every trace.
"""
from __future__ import annotations

import json
import threading
import time
from pathlib import Path
from typing import Optional

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
LAPS_DIR = DATA_DIR / "laps"

# What a listing entry carries. Everything a picker, the debrief or the race
# engineer needs to choose or rank a lap without opening its trace.
SUMMARY_KEYS = (
    "id", "track_id", "track_name", "track_length", "session_type",
    "lap_number", "lap_time_ms", "lap_time_estimated", "flashbacks", "invalid",
    "tyre", "tyre_age", "weather", "air_temp", "track_temp", "recorded_at",
    "sector1_ms", "sector2_ms", "sector3_ms", "fuel_kg", "ers_deployed_mj",
    "avg_tyre_wear", "source", "driver", "team", "ai_controlled", "car_index",
    "session_uid",
)

_lock = threading.Lock()
_index: dict = {}          # file name -> (mtime_ns, size, summary)


def _ensure_dirs():
    LAPS_DIR.mkdir(parents=True, exist_ok=True)


def _slug(value: str) -> str:
    keep = [c if (c.isalnum() or c == "-") else "-" for c in str(value).lower()]
    return "".join(keep).strip("-") or "x"


def _lap_id(record: dict) -> str:
    ts = time.strftime("%Y%m%d-%H%M%S", time.localtime(record.get("recorded_at", time.time())))
    track = _slug(record.get("track_name", "track"))
    sess = _slug(record.get("session_type", "s"))
    who = "you" if record.get("is_player", True) else _slug(record.get("driver", "ai"))
    lap_ms = record.get("lap_time_ms", 0)
    return f"{ts}-{track}-{sess}-{who}-lap{record.get('lap_number', 0)}-{lap_ms}ms"


def _safe_id(lap_id: str) -> bool:
    # ids are generated by us but still guard against path tricks
    return bool(lap_id) and not ("/" in lap_id or "\\" in lap_id or ".." in lap_id)


def summarize(record: dict) -> dict:
    """The listing entry for a full lap record."""
    entry = {k: record.get(k) for k in SUMMARY_KEYS}
    # laps recorded before multi-car support have no is_player flag
    entry["is_player"] = record.get("is_player", True)
    # the trace is not in the listing; say whether the detail has thermals
    entry["has_thermal"] = bool(record.get("thermal"))
    entry["sample_count"] = len(record.get("samples") or [])
    return entry


def save_lap(record: dict) -> str:
    _ensure_dirs()
    lap_id = _lap_id(record)
    record["id"] = lap_id
    with _lock:
        path = LAPS_DIR / f"{lap_id}.json"
        # avoid collisions when two laps finalize within the same second
        n = 1
        while path.exists():
            n += 1
            path = LAPS_DIR / f"{lap_id}-{n}.json"
            record["id"] = f"{lap_id}-{n}"
        path.write_text(json.dumps(record), encoding="utf-8")
        try:
            st = path.stat()
            _index[path.name] = (st.st_mtime_ns, st.st_size, summarize(record))
        except OSError:
            pass
    return record["id"]


def list_laps() -> list:
    """Every recorded lap, newest first, as listing entries (no trace)."""
    _ensure_dirs()
    out = []
    seen = set()
    with _lock:
        for path in sorted(LAPS_DIR.glob("*.json"), reverse=True):
            try:
                st = path.stat()
            except OSError:
                continue
            seen.add(path.name)
            cached = _index.get(path.name)
            if cached and cached[0] == st.st_mtime_ns and cached[1] == st.st_size:
                out.append(dict(cached[2]))
                continue
            try:
                rec = json.loads(path.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError):
                continue
            entry = summarize(rec)
            _index[path.name] = (st.st_mtime_ns, st.st_size, entry)
            out.append(dict(entry))
        for name in [n for n in _index if n not in seen]:
            del _index[name]
    return out


def load_lap(lap_id: str) -> Optional[dict]:
    if not _safe_id(lap_id):
        return None
    path = LAPS_DIR / f"{lap_id}.json"
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None


def delete_lap(lap_id: str) -> bool:
    if not _safe_id(lap_id):
        return False
    path = LAPS_DIR / f"{lap_id}.json"
    with _lock:
        if not path.exists():
            return False
        path.unlink()
        _index.pop(path.name, None)
    return True
