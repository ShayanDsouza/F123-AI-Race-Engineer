"""Lap storage: one JSON file per recorded lap + an in-memory index.

Laps live in data/laps/<id>.json. The id encodes track/session/time so files
are self-describing even outside the app.
"""
from __future__ import annotations

import json
import threading
import time
from pathlib import Path
from typing import Optional

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
LAPS_DIR = DATA_DIR / "laps"

_lock = threading.Lock()


def _ensure_dirs():
    LAPS_DIR.mkdir(parents=True, exist_ok=True)


def _slug(value: str) -> str:
    keep = [c if (c.isalnum() or c == "-") else "-" for c in str(value).lower()]
    return "".join(keep).strip("-") or "x"


def _lap_id(record: dict) -> str:
    ts = time.strftime("%Y%m%d-%H%M%S", time.localtime(record.get("recorded_at", time.time())))
    track = _slug(record.get("track_name", "track"))
    sess = _slug(record.get("session_type", "s"))
    who = "you" if record.get("is_player", True) else _slug(record.get("driver", "ai"))
    lap_ms = record.get("lap_time_ms", 0)
    return f"{ts}-{track}-{sess}-{who}-lap{record.get('lap_number', 0)}-{lap_ms}ms"


def save_lap(record: dict) -> str:
    _ensure_dirs()
    lap_id = _lap_id(record)
    record["id"] = lap_id
    with _lock:
        path = LAPS_DIR / f"{lap_id}.json"
        # avoid collisions when two laps finalize within the same second
        n = 1
        while path.exists():
            n += 1
            path = LAPS_DIR / f"{lap_id}-{n}.json"
            record["id"] = f"{lap_id}-{n}"
        path.write_text(json.dumps(record), encoding="utf-8")
    return record["id"]


def list_laps() -> list:
    _ensure_dirs()
    out = []
    for path in sorted(LAPS_DIR.glob("*.json"), reverse=True):
        try:
            rec = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        entry = {k: rec.get(k) for k in (
            "id", "track_id", "track_name", "track_length", "session_type",
            "lap_number", "lap_time_ms", "invalid", "tyre", "tyre_age",
            "weather", "recorded_at", "sector1_ms", "sector2_ms", "sector3_ms",
            "source", "driver", "team", "ai_controlled", "session_uid")}
        # laps recorded before multi-car support have no is_player flag
        entry["is_player"] = rec.get("is_player", True)
        out.append(entry)
    return out


def load_lap(lap_id: str) -> Optional[dict]:
    # ids are generated by us but still guard against path tricks
    if "/" in lap_id or "\\" in lap_id or ".." in lap_id:
        return None
    path = LAPS_DIR / f"{lap_id}.json"
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None


def delete_lap(lap_id: str) -> bool:
    if "/" in lap_id or "\\" in lap_id or ".." in lap_id:
        return False
    path = LAPS_DIR / f"{lap_id}.json"
    if path.exists():
        path.unlink()
        return True
    return False
